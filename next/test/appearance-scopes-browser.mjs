import assert from "node:assert/strict";
import path from "node:path";
import {chromium} from "@playwright/test";
const base=process.env.DAR_INTEGRATION_ORIGIN;
if(!base||!process.env.DAR_TEST_ROOT)throw new Error("An isolated fixture is required.");
const browser=await chromium.launch({executablePath:process.env.DAR_CHROMIUM,headless:true});
const png=Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1sAAAAASUVORK5CYII=","base64");
try{
  const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto(base);
  await page.locator(".signin-brand .brand").waitFor();
  await page.getByLabel("Username",{exact:true}).fill("admin");
  await page.getByLabel("Password",{exact:true}).fill("a long isolated test password");
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await page.getByRole("button",{name:"Open account menu",exact:true}).waitFor();
  await page.goto(base+"/settings?section=instanceAppearance");
  await page.getByLabel("Upload logo",{exact:true}).setInputFiles({name:"logo.png",mimeType:"image/png",buffer:png});
  await page.getByRole("button",{name:"Save appearance",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Appearance saved"}).waitFor();
  await page.reload();
  await page.locator('.signin-logo-preview img[src^="/api/v1/appearance/logo"]').waitFor();
  const anonymous=await browser.newContext(),loginPage=await anonymous.newPage();
  await loginPage.goto(base);
  await loginPage.locator(".signin-brand img").waitFor();
  await loginPage.waitForFunction(()=>{const img=document.querySelector(".signin-brand img");return img?.complete&&img.naturalWidth>0;});
  await loginPage.screenshot({path:path.join(process.env.DAR_TEST_ROOT,"signin-logo-desktop.png")});
  await loginPage.setViewportSize({width:390,height:844});
  assert.equal(await loginPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.goto(base+"/settings?section=security");
  await page.getByLabel("Device or application name",{exact:true}).fill("Browser mixed scopes");
  await page.getByRole("checkbox",{name:"Files read",exact:true}).check();
  await page.getByRole("checkbox",{name:"Contacts read",exact:true}).check();
  await page.getByRole("checkbox",{name:"Contacts write",exact:true}).check();
  await page.getByRole("checkbox",{name:"Calendar write",exact:true}).check();
  await page.getByRole("button",{name:"Create app password",exact:true}).click();
  await page.getByLabel("App password",{exact:true}).waitFor();
  await page.getByRole("button",{name:"I saved it",exact:true}).click();
  await page.reload();
  await page.getByText("Files: Read · Contacts: Read and write · Calendar: Write",{exact:false}).waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(process.env.DAR_TEST_ROOT,"app-scopes-phone.png"),fullPage:true});
  await page.goto(base+"/settings?section=instanceAppearance");
  await page.getByRole("button",{name:"Use Dar logo",exact:true}).click();
  await page.getByRole("button",{name:"Save appearance",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Appearance saved"}).waitFor();
  await loginPage.reload();
  await loginPage.locator(".signin-brand .brand").waitFor();
  assert.deepEqual(errors,[]);
  console.info("PASS custom sign-in logo, persisted admin appearance, logo reset and multi-app scope matrix at desktop/phone sizes.");
}finally{await browser.close();}
