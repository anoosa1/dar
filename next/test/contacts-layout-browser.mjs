import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {randomUUID} from "node:crypto";
import {chromium} from "@playwright/test";
import {choose} from "./ui-helpers.mjs";
const base=process.env.DAR_INTEGRATION_ORIGIN;
if(!base||!process.env.DAR_TEST_ROOT)throw Error("An isolated fixture is required.");
const browser=await chromium.launch({executablePath:process.env.DAR_CHROMIUM,headless:true});
try{
  const context=await browser.newContext({viewport:{width:1440,height:950},acceptDownloads:true}),page=await context.newPage(),errors=[];
  page.on("pageerror",error=>errors.push(error.message));
  await page.goto(base+"/contacts");
  await page.getByLabel("Username",{exact:true}).fill("admin");
  await page.getByLabel("Password",{exact:true}).fill("a long isolated test password");
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await page.getByRole("heading",{name:"All contacts",exact:true}).waitFor();
  const fixture=await page.evaluate(async()=>{
    const {csrfToken}=await(await fetch("/api/v1/auth/session")).json();
    async function post(path,body){const response=await fetch(path,{method:"POST",headers:{"content-type":"application/json","x-csrf-token":csrfToken},body:JSON.stringify(body)});if(response.status!==201)throw Error(await response.text());return response.json();}
    const a=await post("/api/v1/contacts/books",{name:"Scrolling people",color:"#1e66f5"}),b=await post("/api/v1/contacts/books",{name:"Menu target book",color:"#1e66f5"});
    for(let i=0;i<45;i++)await post("/api/v1/contacts/books/"+a.id+"/items",{data:{displayName:"Scroll person "+String(i).padStart(2,"0"),notes:"Long contact details\n".repeat(150)}});
    return {a,b};
  });
  await page.goto(base+"/contacts?book="+fixture.a.id);
  await page.getByRole("button",{name:/Scroll person 00/}).click();
  await page.getByRole("heading",{name:"Scroll person 00",exact:true}).waitFor();
  const details=page.getByRole("complementary",{name:"Contact details",exact:true}),list=page.locator(".contact-list");
  const position=await details.boundingBox();
  await list.evaluate(el=>el.scrollTop=1000);
  assert.ok(await list.evaluate(el=>el.scrollTop)>0);
  assert.deepEqual(await details.boundingBox(),position);
  const listScroll=await list.evaluate(el=>el.scrollTop);
  await details.evaluate(el=>el.scrollTop=500);
  assert.ok(await details.evaluate(el=>el.scrollTop)>0);
  assert.equal(await list.evaluate(el=>el.scrollTop),listScroll);
  assert.equal(await page.evaluate(()=>scrollY),0);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight>innerHeight+1),false);
  assert.equal(await page.locator(".sidebar").getByRole("link",{name:"Export vCard",exact:true}).count(),0);
  assert.equal(await page.locator(".sidebar").getByRole("button",{name:"Import vCard",exact:true}).count(),0);
  const actions=page.getByRole("button",{name:"Actions for address book Menu target book",exact:true});
  const previous=page.getByRole("button",{name:"Previous address books",exact:true}),next=page.getByRole("button",{name:"Next address books",exact:true});
  while(await previous.count()&&await previous.isEnabled())await previous.click();
  while(!await actions.isVisible()&&await next.count()&&await next.isEnabled())await next.click();
  await actions.click();await page.getByRole("menuitem",{name:"Edit address book",exact:true}).click();
  assert.equal(await page.locator("[data-editor-pane]").getByLabel("Name",{exact:true}).inputValue(),fixture.b.name);
  await page.getByRole("button",{name:"Close editor",exact:true}).click();
  await actions.click();await page.getByRole("menuitem",{name:"Share address book",exact:true}).click();
  await page.getByRole("dialog",{name:"Share Menu target book",exact:true}).waitFor();
  await page.keyboard.press("Escape");
  await page.getByRole("dialog",{name:"Share Menu target book",exact:true}).waitFor({state:"hidden"});
  await actions.click();await page.getByRole("menuitem",{name:"Delete address book",exact:true}).click();
  const deletion=page.getByRole("dialog",{name:"Delete address book?",exact:true});
  await deletion.getByText("Remove Menu target book and all its 0 contacts? Export it first if you need a copy.",{exact:true}).waitFor();
  await deletion.getByRole("button",{name:"Cancel",exact:true}).click();
  await deletion.waitFor({state:"hidden"});
  await actions.focus();await page.keyboard.press("ArrowDown");
  await page.getByRole("menuitem",{name:"Edit address book",exact:true}).waitFor();
  await page.keyboard.press("Escape");
  assert.equal(await actions.evaluate(el=>el===document.activeElement),true);
  await page.getByRole("button",{name:"Contacts settings",exact:true}).click();
  const settings=page.getByRole("dialog",{name:"Contacts settings",exact:true});
  await settings.getByRole("button",{name:"Import and export",exact:true}).click();
  await choose(settings.getByRole("combobox",{name:"Address book for import or export",exact:true}),{label:fixture.a.name});
  const download=page.waitForEvent("download");await settings.getByRole("link",{name:"Export vCard",exact:true}).click();
  assert.match(await readFile(await(await download).path(),"utf8"),/Scroll person 00/);
  await settings.getByLabel("Or paste content",{exact:true}).fill("BEGIN:VCARD\r\nVERSION:3.0\r\nUID:"+randomUUID()+"\r\nFN:Settings vCard proof\r\nEND:VCARD\r\n");
  await settings.getByRole("button",{name:"Import vCard",exact:true}).click();
  await settings.getByText("1 imported; 0 failed.",{exact:true}).waitFor();
  await settings.getByRole("button",{name:"Close dialog",exact:true}).click();
  await page.reload();
  await page.getByRole("button",{name:/Settings vCard proof/}).waitFor();
  for(const viewport of [{width:1000,height:700},{width:390,height:844}]){
    await page.setViewportSize(viewport);
    if(viewport.width<=800)await page.getByRole("button",{name:"Open navigation",exact:true}).click();
    const footer=await page.getByRole("button",{name:"Contacts settings",exact:true}).boundingBox();
    assert.ok(footer&&footer.y+footer.height<=viewport.height);
    assert.equal(await page.locator(".sidebar").evaluate(el=>el.scrollHeight>el.clientHeight+1),false);
    if(viewport.width<=800)await page.getByRole("button",{name:"Open navigation",exact:true}).click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight>innerHeight+1),false);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:process.env.DAR_TEST_ROOT+"/contacts-independent-panes-"+viewport.width+".png"});
  }
  assert.deepEqual(errors,[]);
  console.info("PASS Contacts collection menu targeting, keyboard focus, settings vCard round trip and independent middle/right scrolling on desktop/tablet/phone.");
}finally{await browser.close();}
