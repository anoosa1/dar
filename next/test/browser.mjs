import assert from "node:assert/strict";
import {fileDetails} from "./ui-helpers.mjs";
import { chromium } from "@playwright/test";
import { randomUUID } from "node:crypto";
const origin = process.env.DAR_INTEGRATION_ORIGIN;
if (!origin) throw new Error("DAR_INTEGRATION_ORIGIN must identify an isolated test instance.");
const browser = await chromium.launch({ executablePath: process.env.DAR_CHROMIUM, headless: true });
const failures = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 950 } });
  const page = await context.newPage();
  let socket, reconnected;
  await page.routeWebSocket("**/v1/database/*/subscribe*", route => {
    socket = { client: route, server: route.connectToServer() };
    reconnected?.();
  });
  page.on("pageerror", error => failures.push(error.message));
  page.on("console", message => { if (message.type() === "error" && !/401.*Unauthorized/.test(message.text())) failures.push(message.text()); });
  await page.goto(origin);
  await page.getByLabel("Username", { exact: true }).fill("admin");
  await page.getByLabel("Password", { exact: true }).fill("a long isolated test password");
  await page.screenshot({ path: "/tmp/dar-auth-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.waitForFunction(() => !document.body.textContent.includes("Connecting…"));
  await page.getByRole("button", { name: "New folder", exact: true }).click();
  const folder = `Browser ${randomUUID().slice(0, 6)}`;
  await page.getByRole("dialog").getByLabel("Name", { exact: true }).fill(folder);
  await page.getByRole("button", { name: "Create folder", exact: true }).click();
  await page.getByRole("button", { name: folder, exact: true }).click();
  await page.getByRole("heading", { name: folder, exact: true }).waitFor();
  await page.reload();
  await page.getByRole("heading", { name: folder, exact: true }).waitFor();
  await page.getByLabel("Choose files to upload", { exact: true }).setInputFiles({ name: "Welcome.txt", mimeType: "text/plain", buffer: Buffer.from("A real file uploaded through the Files app.") });
  await page.getByRole("button", { name: "Welcome.txt", exact: true }).waitFor();
  await page.getByRole("button", { name: "Dismiss finished uploads", exact: true }).click();
  let releaseReservation;
  const reservationGate = new Promise(resolve => { releaseReservation = resolve; });
  let intercepted;
  const reservationStarted = new Promise(resolve => { intercepted = resolve; });
  await page.route("**/api/v1/files/uploads", async route => { intercepted(); await reservationGate; await route.abort().catch(() => {}); }, { times: 1 });
  await page.getByLabel("Choose files to upload", { exact: true }).setInputFiles({ name: "Cancelled.txt", mimeType: "text/plain", buffer: Buffer.alloc(4096) });
  await reservationStarted;
  await page.getByRole("button", { name: "Cancel upload Cancelled.txt", exact: true }).click();
  await page.getByText("Upload cancelled.", { exact: true }).waitFor(); releaseReservation();
  await page.getByRole("button", { name: "Dismiss finished uploads", exact: true }).click();
  await fileDetails(page,"Welcome.txt");
  await page.getByRole("heading", { name: "Welcome.txt", exact: true }).waitFor();
  await page.screenshot({ path: "/tmp/dar-files-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Rename", exact: true }).click();
  await page.getByRole("dialog").getByLabel("Name", { exact: true }).fill("A little hello.txt");
  await page.getByRole("dialog").getByRole("button", { name: "Save", exact: true }).click();
  await page.getByRole("heading", { name: "A little hello.txt", exact: true }).waitFor();
  await page.getByRole("button", { name: "Preview", exact: true }).click();
  await page.getByRole("dialog").getByText("A real file uploaded through the Files app.", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Close dialog", exact: true }).click();
  await page.waitForFunction(() => document.activeElement?.textContent?.trim() === "Preview");
  await page.getByRole("button", { name: "Add to favorites", exact: true }).click();
  await page.getByRole("button", { name: "Remove favorite", exact: true }).waitFor();
  await page.getByRole("button", { name: "Close details", exact: true }).click();
  await page.getByRole("button", { name: "Favorites", exact: true }).click();
  await page.getByRole("button", { name: "A little hello.txt", exact: true }).waitFor();
  await fileDetails(page,"A little hello.txt");
  await page.getByRole("button", { name: "Move to deleted files", exact: true }).click();
  await page.getByRole("button", { name: "Deleted files", exact: true }).click();
  await fileDetails(page,"A little hello.txt");
  await page.getByRole("button", { name: "Restore", exact: true }).click();
  await page.getByRole("button", { name: "All files", exact: true }).first().click();
  await page.getByRole("button", { name: folder, exact: true }).click();
  await page.getByRole("button", { name: "A little hello.txt", exact: true }).waitFor();
  const nextSocket = new Promise(resolve => { reconnected = resolve; });
  await Promise.all([socket.client.close({ code: 1012, reason: "Acceptance reconnect" }), socket.server.close({ code: 1012, reason: "Acceptance reconnect" })]);
  await page.getByRole("button", { name: "Favorites", exact: true }).click();
  await nextSocket;
  await page.waitForFunction(() => !/Connecting…|Reconnecting…|Refreshing your files…/.test(document.body.textContent));
  await page.getByRole("button", { name: "A little hello.txt", exact: true }).waitFor();
  await page.getByRole("button", { name: "All files", exact: true }).first().click();
  await page.getByRole("button", { name: folder, exact: true }).click();
  await page.getByRole("button", { name: "A little hello.txt", exact: true }).waitFor();
  const state = await context.storageState();
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, storageState: state, isMobile: true, hasTouch: true });
  const phone = await mobile.newPage();
  phone.on("pageerror", error => failures.push(error.message));
  await phone.goto(origin);
  await phone.getByRole("button", { name: "Open navigation", exact: true }).waitFor();
  await phone.waitForFunction(() => !document.body.textContent.includes("Connecting…"));
  await phone.getByRole("button", { name: folder, exact: true }).click();
  await phone.getByRole("button", { name: "A little hello.txt", exact: true }).waitFor();
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await phone.screenshot({ path: "/tmp/dar-files-mobile.png", fullPage: true });
  await fileDetails(phone,"A little hello.txt");
  await phone.getByRole("heading", { name: "A little hello.txt", exact: true }).waitFor();
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await phone.screenshot({ path: "/tmp/dar-files-mobile-details.png", fullPage: true });
  await phone.getByRole("button", { name: "Close details", exact: true }).click();
  await mobile.close();
  await page.getByRole("button", { name: "Open account menu", exact: true }).click();
  await page.getByRole("menuitem", { name: "Sign out", exact: true }).click();
  await page.getByRole("heading", { name: "Welcome back", exact: true }).waitFor();
  assert.deepEqual(failures, []);
  console.info("PASS desktop/mobile auth, upload/cancel, preview, rename, favorite, trash/restore, reconnect during navigation, and logout; no page/console errors or mobile overflow.");
  await context.close();
} finally { await browser.close(); }
